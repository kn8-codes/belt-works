      <h2>Information that can carry its weight.</h2>
      <p>
        A messy export becomes a clean working file. Repeated records become one trustworthy list.
        Information scattered across pages and tools becomes something a person can search, act on, or
        hand to the next system without starting over.
      </p>
    </article>
    <ul class="list">
      <li>Find the source information that matters.</li>
      <li>Clean and organize it around the decisions people need to make.</li>
      <li>Check enough of it to understand what is reliable and what needs a human eye.</li>
      <li>Deliver it as a useful file, export, report, or working system.</li>
